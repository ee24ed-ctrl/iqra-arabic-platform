  function getStoryQuiz(storyId) {
    var s = STORIES.find(function (x) { return x.id === Number(storyId); }) || STORIES[0];
    var quiz = [];

    // 5 Multiple Choice (mcq)
    quiz.push({
      type: 'mcq',
      typeLabel: 'اختيار من متعدد (1/5)',
      question: s.q1,
      options: s.opts1,
      answer: s.ans1
    });
    quiz.push({
      type: 'mcq',
      typeLabel: 'اختيار من متعدد (2/5)',
      question: s.q2,
      options: s.opts2,
      answer: s.ans2
    });
    quiz.push({
      type: 'mcq',
      typeLabel: 'اختيار من متعدد (3/5)',
      question: s.q3,
      options: s.opts3,
      answer: s.ans3
    });
    quiz.push({
      type: 'mcq',
      typeLabel: 'اختيار من متعدد (4/5)',
      question: 'ما الفكرة الرئيسة أو القيمة المستفادة من قصة «' + s.title + '»؟',
      options: [s.moral, 'إضاعة الوقت دون فائدة', 'الاستسلام عند أول صعوبة'],
      answer: 0
    });
    quiz.push({
      type: 'mcq',
      typeLabel: 'اختيار من متعدد (5/5)',
      question: 'أي تصنيف ومستوى ينتمي إليهما موضوع قصة «' + s.title + '»؟',
      options: ['مجال ' + s.cat + ' (' + s.level + ')', 'الرياضة الأولمبية (مستوى هـ)', 'الطبخ السريع (مستوى و)'],
      answer: 0
    });

    // 3 True / False (tf)
    quiz.push({
      type: 'tf',
      typeLabel: 'صح أم خطأ (1/3)',
      question: 'ورد في أحداث القصة: «' + s.pages[0] + '»',
      options: ['صح ✓', 'خطأ ✗'],
      answer: 0
    });
    quiz.push({
      type: 'tf',
      typeLabel: 'صح أم خطأ (2/3)',
      question: 'هل حدث هذا في القصة: «' + s.falseStmt + '»',
      options: ['صح ✓', 'خطأ ✗'],
      answer: 1
    });
    quiz.push({
      type: 'tf',
      typeLabel: 'صح أم خطأ (3/3)',
      question: 'تعلمنا من نهاية قصة «' + s.title + '» أهمية: ' + s.moral + '.',
      options: ['صح ✓', 'خطأ ✗'],
      answer: 0
    });

    // 3 Sentence / Word Ordering (order)
    var orderSentences = [s.pages[0], s.pages[1], s.pages[3]];
    orderSentences.forEach(function (sent, idx) {
      var correctTokens = splitIntoOrderTokens(sent);
      var scrambled = seededShuffle(correctTokens, s.id + idx + 2);
      quiz.push({
        type: 'order',
        typeLabel: 'رتب الجملة والكلمات (' + (idx + 1) + '/3)',
        question: 'رتّب الكلمات والعبارات التالية لتكوين جملة صحيحة من القصة:',
        tokens: scrambled,
        correctTokens: correctTokens
      });
    });

    return quiz;
  }

