  function splitIntoOrderTokens(sentence) {
    var clean = sentence.replace(/[،.؟!]/g, '').trim();
    var words = clean.split(/\s+/);
    if (words.length <= 5) return words;
    // Group into 4-5 meaningful chunks for smooth kid-friendly ordering
    var chunks = [];
    var size = Math.ceil(words.length / 4);
    for (var i = 0; i < words.length; i += size) {
      chunks.push(words.slice(i, i + size).join(' '));
    }
    return chunks;
  }

  function seededShuffle(arr, seed) {
    var out = arr.slice();
    for (var i = out.length - 1; i > 0; i--) {
      var j = (seed * (i + 3) + 7) % (i + 1);
      var tmp = out[i];
      out[i] = out[j];
      out[j] = tmp;
    }
    if (out.join('|') === arr.join('|') && out.length > 1) {
      var t = out[0];
      out[0] = out[out.length - 1];
      out[out.length - 1] = t;
    }
    return out;
  }

