  function saveTaskCompletion(sid, storyId, score, total, points) {
    seedDefaultProgressIfNeeded();
    var prog = getStudentProgress(sid);
    var now = new Date();
    var timeStr = now.toLocaleTimeString('ar-SA', { hour: '2-digit', minute: '2-digit' });
    prog[String(storyId)] = {
      done: true,
      score: score,
      total: total,
      points: points,
      completedAt: 'اليوم ' + timeStr
    };
    localStorage.setItem('iread_weekly_progress_' + sid, JSON.stringify(prog));

    // Sync with books & rewards
    var booksMap = JSON.parse(localStorage.getItem('iread_books_' + sid) || '{}');
    booksMap[String(storyId)] = true;
    localStorage.setItem('iread_books_' + sid, JSON.stringify(booksMap));

    var rw = JSON.parse(localStorage.getItem('iread_rewards_' + sid) || '{"stars":3,"notes":[]}');
    rw.stars = Number(rw.stars || 0) + 2;
    rw.weeklyPoints = Number(rw.weeklyPoints || 0) + points;
    rw.notes = Array.isArray(rw.notes) ? rw.notes : [];
    var st = STORIES.find(function (x) { return x.id === Number(storyId); });
    rw.notes.push('أتمّ قراءة القصة الأسبوعية «' + (st ? st.title : storyId) + '» بنتيجة ' + score + '/' + total + ' (+' + points + ' نقطة)');
    localStorage.setItem('iread_rewards_' + sid, JSON.stringify(rw));

    return prog;
  }

