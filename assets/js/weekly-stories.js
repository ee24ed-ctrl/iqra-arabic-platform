  function getWeeklyReport() {
    var assign = getAssignments();
    var ids = assign.storyIds;
    return getAllStudents().map(function (st) {
      var prog = getStudentProgress(st.id);
      var t1 = prog[String(ids[0])] || null;
      var t2 = ids[1] ? (prog[String(ids[1])] || null) : null;
      var doneCount = (t1 && t1.done ? 1 : 0) + (ids[1] && t2 && t2.done ? 1 : 0);
      var requiredCount = ids.length;
      var allDone = doneCount >= requiredCount;
      var totalPoints = (t1 ? t1.points : 0) + (t2 ? t2.points : 0);
      var avgPct = 0;
      if (doneCount > 0) {
        var sumPct = (t1 && t1.done ? (t1.score / t1.total) * 100 : 0) + (t2 && t2.done ? (t2.score / t2.total) * 100 : 0);
        avgPct = Math.round(sumPct / doneCount);
      }
      return {
        student: st,
        task1: t1,
        task2: t2,
        doneCount: doneCount,
        requiredCount: requiredCount,
        allDone: allDone,
        totalPoints: totalPoints,
        avgPct: avgPct
      };
    });
  }

