  function saveSkillCompletion(sid, skillId, score, total, points) {
    var all = getAllSkills();
    var sk = all.find(function (x) { return x.id === skillId; }) || all[0];
    var doneKey = 'iread_done_' + sid;
    var doneMap = JSON.parse(localStorage.getItem(doneKey) || '{}');
    doneMap[skillId] = score + '/' + total;
    localStorage.setItem(doneKey, JSON.stringify(doneMap));

    var prog = getSkillProgress(sid);
    var now = new Date().toLocaleTimeString('ar-SA', { hour: '2-digit', minute: '2-digit' });
    prog[skillId] = {
      done: true,
      title: sk.title,
      score: score,
      total: total,
      points: points,
      completedAt: 'اليوم ' + now
    };
    localStorage.setItem('iread_skill_progress_' + sid, JSON.stringify(prog));

    var rw = JSON.parse(localStorage.getItem('iread_rewards_' + sid) || '{"stars":3,"notes":[]}');
    rw.stars = Number(rw.stars || 0) + 1;
    rw.weeklyPoints = Number(rw.weeklyPoints || 0) + points;
    rw.notes = Array.isArray(rw.notes) ? rw.notes : [];
    rw.notes.push('أتمّ لعبة مهارة «' + sk.title + '» بنتيجة ' + score + '/' + total + ' (+' + points + ' نقطة)');
    localStorage.setItem('iread_rewards_' + sid, JSON.stringify(rw));

    return prog;
  }

  function getSkillReport() {
    var assignedId = getGlobalAssignedSkill();
    var all = getAllSkills();
    var assignedSkill = all.find(function (x) { return x.id === assignedId; }) || all[0];
    var students = window.IREAD_WEEKLY && window.IREAD_WEEKLY.getAllStudents
      ? window.IREAD_WEEKLY.getAllStudents()
      : [{ id: 1, name: 'سارة أحمد', grade: 'الصف الأول' }, { id: 4, name: 'يوسف طارق', grade: 'الصف الرابع' }];

    return {
      assignedSkill: assignedSkill,
      rows: students.map(function (st) {
        var prog = getSkillProgress(st.id);
        var rec = prog[assignedId] || null;
        return {
          student: st,
          record: rec,
          done: !!(rec && rec.done)
        };
      })
    };
  }

