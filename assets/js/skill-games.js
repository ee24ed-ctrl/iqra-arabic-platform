  function splitWords(sent) {
    return sent.replace(/[،.؟!]/g, '').trim().split(/\s+/);
  }

  function shuffleArr(arr, seed) {
    var out = arr.slice();
    for (var i = out.length - 1; i > 0; i--) {
      var j = (seed * (i + 3) + 5) % (i + 1);
      var t = out[i]; out[i] = out[j]; out[j] = t;
    }
    if (out.join('|') === arr.join('|') && out.length > 1) {
      var tmp = out[0]; out[0] = out[out.length - 1]; out[out.length - 1] = tmp;
    }
    return out;
  }

  // Returns 10 questions: 5 MCQ + 2 TF + 2 Order + 1 Match
  function getSkillQuiz(skillId) {
    var sk = SKILLS.find(function (x) { return x.id === skillId; }) || SKILLS[0];
    var quiz = [];

    sk.mcqs.forEach(function (m, idx) {
      quiz.push({
        type: 'mcq',
        typeLabel: 'اختيار من متعدد (' + (idx + 1) + '/5)',
        question: m[0],
        options: m[1],
        answer: m[2]
      });
    });

    sk.tfs.forEach(function (t, idx) {
      quiz.push({
        type: 'tf',
        typeLabel: 'صح أم خطأ (' + (idx + 1) + '/2)',
        question: t[0],
        options: ['صح ✓', 'خطأ ✗'],
        answer: t[1] ? 0 : 1
      });
    });

    sk.orders.forEach(function (sent, idx) {
      var words = splitWords(sent);
      quiz.push({
        type: 'order',
        typeLabel: 'رتّب الكلمات لتكوين جملة (' + (idx + 1) + '/2)',
        question: 'رتّب الكلمات التالية لتكوين جملة عربية صحيحة:',
        tokens: shuffleArr(words, idx + sk.title.length),
        correctTokens: words
      });
    });

    quiz.push({
      type: 'match',
      typeLabel: 'صِل بين الكلمات وما يناسبها (1/1)',
      question: 'اختر كل كلمة من العمود الأيمن ثم اضغط على ما يناسبها في العمود الأيسر:',
      pairs: sk.match
    });

    return quiz;
  }

  function getGlobalAssignedSkill() {
    return localStorage.getItem(ASSIGNED_SKILL_KEY) || 'short-vowels';
  }

  function setGlobalAssignedSkill(skillId) {
    localStorage.setItem(ASSIGNED_SKILL_KEY, skillId);
    return skillId;
  }

  function getSkillProgress(sid) {
    try {
      return JSON.parse(localStorage.getItem('iread_skill_progress_' + sid) || '{}');
    } catch (e) {
      return {};
    }
  }

  function saveSkillCompletion(sid, skillId, score, total, points) {
    var sk = SKILLS.find(function (x) { return x.id === skillId; }) || SKILLS[0];
    var doneKey = 'iread_done_' + sid;
    var doneMap = JSON.parse(localStorage.getItem(doneKey) || '{}');
    doneMap[skillId] = score + '/' + total;
    localStorage.setItem(doneKey, JSON.stringify(doneMap));

    var prog = getSkillProgress(sid);
    var now = new Date().toLocaleTimeString('ar-SA', { hour: '2-digit', minute: '2-digit' });
    prog[skillId] = {
      done: true,
      title: sk.title,
      score: score,
      total: total,
      points: points,
      completedAt: 'اليوم ' + now
    };
    localStorage.setItem('iread_skill_progress_' + sid, JSON.stringify(prog));

    var rw = JSON.parse(localStorage.getItem('iread_rewards_' + sid) || '{"stars":3,"notes":[]}');
    rw.stars = Number(rw.stars || 0) + 1;
    rw.weeklyPoints = Number(rw.weeklyPoints || 0) + points;
    rw.notes = Array.isArray(rw.notes) ? rw.notes : [];
    rw.notes.push('أتمّ لعبة مهارة «' + sk.title + '» بنتيجة ' + score + '/' + total + ' (+' + points + ' نقطة)');
    localStorage.setItem('iread_rewards_' + sid, JSON.stringify(rw));

    return prog;
  }

  function getSkillReport() {
    var assignedId = getGlobalAssignedSkill();
    var assignedSkill = SKILLS.find(function (x) { return x.id === assignedId; }) || SKILLS[0];
    var students = window.IREAD_WEEKLY && window.IREAD_WEEKLY.getAllStudents
      ? window.IREAD_WEEKLY.getAllStudents()
      : [{ id: 1, name: 'سارة أحمد', grade: 'الصف الأول' }, { id: 4, name: 'يوسف طارق', grade: 'الصف الرابع' }];

    return {
      assignedSkill: assignedSkill,
      rows: students.map(function (st) {
        var prog = getSkillProgress(st.id);
        var rec = prog[assignedId] || null;
        return {
          student: st,
          record: rec,
          done: !!(rec && rec.done)
        };
      })
    };
  }

