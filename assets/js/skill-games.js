  function distributeSkillsToTeacher(teacherId, skillIds, targetTeacherIds) {
    var map = getAllTeacherSkillDistributions();
    var cleanIds = Array.isArray(skillIds) ? skillIds.filter(Boolean) : [];
    var targets = teacherId === 'all' && Array.isArray(targetTeacherIds)
      ? targetTeacherIds
      : (teacherId && teacherId !== 'all' ? [teacherId] : []);
    if (!targets.length) return { ok: false, error: 'يرجى اختيار معلم واحد على الأقل.' };
    if (!cleanIds.length) return { ok: false, error: 'يرجى تحديد مهارة واحدة على الأقل للتوزيع.' };
    targets.forEach(function (tid) {
      map[tid] = cleanIds.slice();
    });
    try {
      localStorage.setItem(TEACHER_DIST_KEY, JSON.stringify(map));
    } catch (e) {}
    return { ok: true, targets: targets, count: cleanIds.length };
  }

